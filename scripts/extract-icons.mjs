import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectDirectory = join(scriptDirectory, '..');
const siteCss = readFileSync(join(projectDirectory, 'design/site.css'), 'utf8');
const outputPath = join(projectDirectory, 'src/shared/icons/icon-registry.ts');

const allowedTags = new Set([
  'path',
  'circle',
  'rect',
  'line',
  'polyline',
  'polygon',
  'ellipse',
  'g',
]);
const allowedAttributes = new Set([
  'd',
  'cx',
  'cy',
  'r',
  'rx',
  'ry',
  'x',
  'y',
  'x1',
  'y1',
  'x2',
  'y2',
  'width',
  'height',
  'points',
  'fill',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'fill-rule',
  'clip-rule',
  'transform',
  'opacity',
]);

function sanitiseColour(value) {
  return value === 'none' ? 'none' : 'currentColor';
}

function readAttributes(source, inheritedAttributes) {
  const attributes = new Map(inheritedAttributes);
  for (const match of source.matchAll(/([\w-]+)=(['"])(.*?)\2/g)) {
    const [, name, , value] = match;
    if (name && value !== undefined && allowedAttributes.has(name)) {
      attributes.set(name, name === 'fill' || name === 'stroke' ? sanitiseColour(value) : value);
    }
  }

  return [...attributes.entries()]
    .map(([name, value]) => `${name}=${JSON.stringify(value)}`)
    .join(' ');
}

function sanitiseSvg(svg) {
  const outerSvg = svg.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/i);
  if (!outerSvg) {
    throw new Error('The data URI does not contain an SVG root element.');
  }

  const [, svgAttributes, markup] = outerSvg;
  const viewBox = svgAttributes.match(/\bviewBox=(['"])(.*?)\1/i)?.[2];
  if (!viewBox) {
    throw new Error('The SVG has no viewBox.');
  }

  const inheritedAttributes = new Map();
  for (const match of svgAttributes.matchAll(/([\w-]+)=(['"])(.*?)\2/g)) {
    const [, name, , value] = match;
    if (name && value !== undefined && allowedAttributes.has(name)) {
      inheritedAttributes.set(
        name,
        name === 'fill' || name === 'stroke' ? sanitiseColour(value) : value,
      );
    }
  }

  const body = [...markup.matchAll(/<([\w-]+)\b([^>]*)\/?>(?:<\/\1>)?/g)]
    .map((match) => {
      const [, tag, attributes] = match;
      if (!tag || !allowedTags.has(tag)) {
        return '';
      }

      const serialisedAttributes = readAttributes(attributes ?? '', inheritedAttributes);
      return `<${tag}${serialisedAttributes ? ` ${serialisedAttributes}` : ''} />`;
    })
    .join('');

  if (!body) {
    throw new Error('The SVG has no allowed shape elements.');
  }

  return { viewBox, body };
}

const iconRules = siteCss.matchAll(
  /\.ic-([a-z0-9-]+)\{[^}]*?--m:url\("data:image\/svg\+xml,([^"]+)"\)/g,
);
const icons = [];
const failures = [];

for (const match of iconRules) {
  const [, sourceName, encodedSvg] = match;
  if (!sourceName || !encodedSvg) {
    continue;
  }

  const name = sourceName.replace(/_/g, '-').toLowerCase();
  try {
    icons.push([name, sanitiseSvg(decodeURIComponent(encodedSvg))]);
  } catch (error) {
    failures.push(`${name}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

if (failures.length > 0) {
  throw new Error(`Could not convert icons:\n${failures.join('\n')}`);
}

function serialiseString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

const entries = icons
  .map(([name, icon]) => {
    const propertyName = /^[A-Za-z_$][\w$]*$/.test(name) ? name : serialiseString(name);
    return `  ${propertyName}: {\n    viewBox: ${serialiseString(icon.viewBox)},\n    body: ${serialiseString(icon.body)},\n  },`;
  })
  .join('\n');
const output = `// Generated by scripts/extract-icons.mjs from design/site.css. Do not edit by hand.\n\nexport const iconRegistry = {\n${entries}\n} as const;\n\nexport type IconName = keyof typeof iconRegistry;\n`;

writeFileSync(outputPath, output);
console.log(`Generated ${icons.length} icons in src/shared/icons/icon-registry.ts.`);
